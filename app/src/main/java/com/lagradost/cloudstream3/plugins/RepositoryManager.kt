    private val GH_REGEX =
        Regex("^https://raw.githubusercontent.com/([A-Za-z0-9-]+)/([A-Za-z0-9_.-]+)/(.*)$")


    /** Returns a SHA-256 string of the file content.
     * Example: "sha256-b70462c264cb7f90fc2860a8e58d7544ce747ff347d1d11fa093623901853573" **/
    @WorkerThread
    fun sha256(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")

        file.inputStream().use { fis ->
            val buffer = ByteArray(8192)
            var read = fis.read(buffer)
            while (read != -1) {
                digest.update(buffer, 0, read)
                read = fis.read(buffer)
            }
        }
        return "sha256-" + digest.digest().joinToString("") { "%02x".format(it) }
    }

    /* Convert raw.githubusercontent.com urls to cdn.jsdelivr.net if enabled in settings.
     * (v0.2.1-e) jsDelivr wants gh/<user>/<repo>@<branch>/<path>. The old code put
     * the whole remainder after @, producing e.g. ...@refs/heads/builds/repo.json
     * (invalid). Strip a refs/heads/ prefix first, then split branch / path. */
    fun convertRawGitUrl(url: String): String {
        if (!EngineApp.jsdelivrProxy) return url
        val match = GH_REGEX.find(url) ?: return url
        val (user, repo, rest) = match.destructured
        val withoutRefs = rest.removePrefix("refs/heads/")
        val branch = withoutRefs.substringBefore("/")
        val path = withoutRefs.substringAfter("/", "")
        return if (path.isBlank()) "https://cdn.jsdelivr.net/gh/$user/$repo@$branch"
        else "https://cdn.jsdelivr.net/gh/$user/$repo@$branch/$path"
    }

    suspend fun parseRepoUrl(url: String): String? {
        val fixedUrl = url.trim()
        return if (fixedUrl.contains("^https?://".toRegex())) {
            fixedUrl
        } else if (fixedUrl.contains("^(cloudstreamrepo://)|(https://cs\\.repo/\\??)".toRegex())) {
            fixedUrl.replace("^(cloudstreamrepo://)|(https://cs\\.repo/\\??)".toRegex(), "").let {
                // (v0.2.1-b) The old code returned fixedUrl here — the
                // STILL-PREFIXED url — when the stripped url already had a
                // scheme. Return the stripped url (it), not fixedUrl.
                return@let if (!it.contains("^https?://".toRegex()))
                    "https://${it}"
                else it
            }
        } else if (fixedUrl.matches("^[a-zA-Z0-9!_-]+$".toRegex())) {
            safeAsync {
                if (fixedUrl.startsWith("!")) {
                    val response = app.get("https://py.md/${fixedUrl.removePrefix("!")}", allowRedirects = false)
                    val url = response.headers["Location"] ?: return@safeAsync null
                    if (url.startsWith("https://py.md/404")) return@safeAsync null
                    if (url.removeSuffix("/") == "https://py.md") return@safeAsync null
                    return@safeAsync url
                } else {
                    val response = app.get("https://cutt.ly/${fixedUrl}", allowRedirects = false)
                    val url = response.headers["Location"] ?: return@safeAsync null
                    if (url.startsWith("https://cutt.ly/404")) return@safeAsync null
                    if (url.removeSuffix("/") == "https://cutt.ly") return@safeAsync null
                    return@safeAsync url
                }
            }
        } else null
    }

    suspend fun parseRepository(url: String): Repository? {
        return parseRepository(url, forceRefresh = false)
    }

    /** Manifest fetch that keeps the old null-on-failure contract. */
    suspend fun parseRepository(url: String, forceRefresh: Boolean): Repository? {
        return try {
            fetchRepository(url, forceRefresh)
        } catch (e: RepoLoadException) {
            logError(e)
            null
        } catch (e: Exception) {
            logError(e)
            null
        }
    }

    // ---- (v0.2.1-o/p) Error kinds + in-memory repo cache ----
    // getRepoPlugins used to return null for EVERY failure (network, HTTP
    // 404, bad JSON) and re-fetched the manifest on every call. Callers can
    // now distinguish the failure, and manifests / plugin lists are cached
    // in memory for 15 min (the same TTL as the HTTP cache).

    enum class RepoLoadError { NETWORK, HTTP, PARSE }

    class RepoLoadException(
        val kind: RepoLoadError,
        val httpCode: Int? = null,
        cause: Throwable? = null,
    ) : Exception("repo load failed: $kind${httpCode?.let { " http=$it" } ?: ""}", cause)

    sealed class RepoPluginsResult {
        data class Ok(val wrappers: List<PluginWrapper>) : RepoPluginsResult()
        data class Err(val kind: RepoLoadError, val httpCode: Int? = null) : RepoPluginsResult()
    }

    private data class CachedRepo(
        val fetchedAtMs: Long,
        val repo: Repository,
        val wrappers: List<PluginWrapper>?,
    )

    private const val REPO_CACHE_TTL_MS = 15 * 60 * 1000L
    private val repoCache = mutableMapOf<String, CachedRepo>()

    fun invalidateRepoCache(url: String? = null) {
        synchronized(repoCache) {
            if (url == null) repoCache.clear() else repoCache.remove(url)
        }
    }

    private fun cachedRepo(url: String): CachedRepo? {
        synchronized(repoCache) {
            val c = repoCache[url] ?: return null
            if (System.currentTimeMillis() - c.fetchedAtMs > REPO_CACHE_TTL_MS) {
                repoCache.remove(url)
                return null
            }
            return c
        }
    }

    private fun putCachedRepo(url: String, repo: Repository, wrappers: List<PluginWrapper>?) {
        synchronized(repoCache) {
            repoCache[url] = CachedRepo(System.currentTimeMillis(), repo, wrappers)
        }
    }

    /** GET a repo/manifest URL. Throws RepoLoadException (NETWORK / HTTP). */
    private suspend fun fetchText(url: String): String {
        val response = try {
            app.get(convertRawGitUrl(url), cacheTime = 15, cacheUnit = TimeUnit.MINUTES)
        } catch (e: java.io.IOException) {
            throw RepoLoadException(RepoLoadError.NETWORK, cause = e)
        }
        if (!response.isSuccessful) {
            throw RepoLoadException(RepoLoadError.HTTP, httpCode = response.code)
        }
        return try {
            response.text
        } catch (e: java.io.IOException) {
            throw RepoLoadException(RepoLoadError.NETWORK, cause = e)
        }
    }

    private suspend fun fetchRepository(url: String, forceRefresh: Boolean): Repository {
        if (!forceRefresh) cachedRepo(url)?.let { return it.repo }
        val text = fetchText(url)
        // kotlinx first (fields now have defaults, v0.2.1-d), Jackson fallback.
        val repo = try {
            AppUtils.parseJson<Repository>(text)
        } catch (e: Exception) {
            throw RepoLoadException(RepoLoadError.PARSE, cause = e)
        }
        putCachedRepo(url, repo, cachedRepo(url)?.wrappers)
        return repo
    }

    private suspend fun parsePlugins(pluginUrls: String): List<SitePlugin> {
        val text = fetchText(pluginUrls)
        // (v0.2.1-c) Decode element-by-element: one bad plugin entry used
        // to throw and emptyList() the WHOLE repo. Bad entries are skipped,
        // good ones kept. A non-empty list with zero decodable entries is a
        // parse failure of the whole list, not an empty repo.
        try {
            val arr = json.parseToJsonElement(text).jsonArray
            val out = mutableListOf<SitePlugin>()
            var bad = 0
            for (el in arr) {
                try {
                    out += json.decodeFromString<SitePlugin>(el.toString())
                } catch (e: Exception) {
                    bad++
                    logError(e)
                }
            }
            if (arr.isNotEmpty() && out.isEmpty()) {
                throw RepoLoadException(RepoLoadError.PARSE)
            }
            if (bad > 0) logError(IllegalStateException("Skipped $bad bad plugin entries in $pluginUrls"))
            return out
        } catch (e: RepoLoadException) {
            throw e
        } catch (e: Exception) {
            // Not a JSON array at all — fall through to the legacy
            // whole-list parse (kotlinx, then Jackson).
            logError(e)
        }
        return try {
            AppUtils.parseJson<Array<SitePlugin>>(text).toList()
        } catch (t: Throwable) {
            logError(t)
            throw RepoLoadException(RepoLoadError.PARSE, cause = t)
        }
    }

    /**
     * Gets all plugins from repositories and pairs them with the repository url.
     * Old null-on-any-failure contract is kept for existing callers.
     */
    suspend fun getRepoPlugins(repositoryData: RepositoryData): List<PluginWrapper>? {
        return when (val r = getRepoPluginsResult(repositoryData)) {
            is RepoPluginsResult.Ok -> r.wrappers
            is RepoPluginsResult.Err -> null
        }
    }

    /** Same as getRepoPlugins, but the failure kind is preserved (v0.2.1-o/p). */
    suspend fun getRepoPluginsResult(
        repositoryData: RepositoryData,
        forceRefresh: Boolean = false,
    ): RepoPluginsResult {
        if (!forceRefresh) {
            cachedRepo(repositoryData.url)?.wrappers?.let { return RepoPluginsResult.Ok(it) }
        }
        return try {
            val repo = fetchRepository(repositoryData.url, forceRefresh)
            val list = repo.pluginLists.amap { url ->
                parsePlugins(url).map {
                    PluginWrapper(repo, repositoryData, it)
                }
            }.flatten()
            putCachedRepo(repositoryData.url, repo, list)
            RepoPluginsResult.Ok(list)
        } catch (e: RepoLoadException) {
            logError(e)
            RepoPluginsResult.Err(e.kind, e.httpCode)
        }
    }

    /**
     * (v0.2.2) Typed download result. The old File? contract swallowed
     * EVERY failure (safeAsync -> null) so a download could fail for any
     * reason — HTTP error, empty body, hash mismatch, move failure — and
     * the bridge could only report a generic "network_error". Callers
     * read [lastDownloadError] (stable code) for the exact reason.
     * Codes: http_<code> | timeout | download_failed | download_empty
     * | hash_mismatch | download_io | download_incomplete (v0.2.6:
     * size check, only when no hash can arbitrate).
     */
    sealed class PluginDownloadResult {
        data class Ok(val file: File) : PluginDownloadResult()
        data class Err(val code: String, val detail: String) : PluginDownloadResult()
    }

    @Volatile
    var lastDownloadError: String? = null
        private set

    // (v0.2.6) One mutex per destination file: two concurrent
    // downloads of the SAME plugin (toggle + test, or two tests)
    // used to share one .part file and interleave their writes,
    // corrupting it. Different plugins still download in parallel.
    private val downloadLocks = ConcurrentHashMap<String, Mutex>()

    suspend fun downloadPluginToFile(
        context: Context,
        pluginUrl: String,
        file: File,
        expectedFileHash: String?,
        expectedFileSize: Long? = null,
    ): PluginDownloadResult {
        val dlLock = downloadLocks.getOrPut(file.absolutePath) { Mutex() }
        return dlLock.withLock {
            downloadPluginToFileLocked(context, pluginUrl, file, expectedFileHash, expectedFileSize)
        }
    }

    private suspend fun downloadPluginToFileLocked(
        context: Context,
        pluginUrl: String,
        file: File,
        expectedFileHash: String?,
        expectedFileSize: Long? = null,
    ): PluginDownloadResult {
        // (v0.2.2) No safeAsync wrapper: every failure is returned as a
        // typed Err with the real cause, never swallowed to null.
        val parentDir = file.parentFile ?: run {
            lastDownloadError = "download_io"
            EngineLogger.log("download", "no parent dir for ${file.name}")
            return PluginDownloadResult.Err("download_io", "No parent directory")
        }
        parentDir.mkdirs()

        // (v0.2.4) Resume state: the partial file lives next to the
        // finished file (same plugin folder, so it is keyed by
        // internalName + repository exactly like the finished file) and
        // the companion .sha256 file records which expected hash the
        // partial bytes belong to — a new version must never resume
        // bytes from the old one. The partial is only ever read with a
        // Range request, is deleted on success / hash mismatch / hash
        // change, and is never a *.cs3 file, so plugin listing never
        // picks it up. (context is kept in the signature for callers;
        // the body no longer needs the cache dir.)
        val partialFile = File(parentDir, file.name + ".part")
        val partialHashFile = File(parentDir, file.name + ".part.sha256")
        // A partial whose hash does not match this download belongs to
        // an older version: drop it, never resume across versions.
        // Without an expected hash there is nothing to verify a resume
        // against, so also start fresh.
        val storedHash = try {
            partialHashFile.takeIf { it.exists() }?.readText()?.trim()
        } catch (_: Exception) {
            null
        }
        if (expectedFileHash == null || storedHash != expectedFileHash) {
            partialFile.delete()
            partialHashFile.delete()
        }
        if (expectedFileHash != null) {
            // Record which hash these partial bytes belong to, so a
            // later tap can resume them (best-effort: a missing hash
            // file just means the next tap starts from byte 0).
            try {
                partialHashFile.writeText(expectedFileHash)
            } catch (_: Exception) {
            }
        }

        // (v0.2.2) FORCE_NETWORK: a .cs3 must always come from the
        // network, never from the OkHttp cache (whose responses are
        // rewritten to max-stale=68y by CacheInterceptor, so a stale or
        // poisoned entry would otherwise be served forever).
        // (v0.2.3) timeout=120s: a .cs3 on a slow network gets a fair
        // chance. (v0.2.4) Callers no longer bound it below 120s:
        // providerTest runs the download outside its 45s content box
        // and the JS side waits 180s, so the HTTP layer is the budget.
        // Manifest fetch timeouts are untouched.
        //
        // (v0.2.4) Up to 3 attempts. Each attempt resumes from the
        // bytes already on disk (Range request); a slow network that
        // drops mid-body therefore continues instead of restarting
        // from byte 0. Only transport failures (SocketTimeoutException
        // / IOException) are retried — HTTP errors, empty bodies and
        // hash mismatches return immediately. Cancellation is never
        // retried or relabelled: it propagates (see N3).
        var attempt = 0
        while (attempt < 3) {
            attempt++
            val downloadedBytes = if (partialFile.exists()) partialFile.length() else 0L
            val headers = if (downloadedBytes > 0L) {
                // Both hosts advertise Accept-Ranges: bytes (verified
                // live); a server that ignores Range answers 200 and is
                // handled below by restarting from byte 0.
                mapOf("Range" to "bytes=$downloadedBytes-")
            } else {
                mapOf()
            }
            val response = try {
                app.get(
                    convertRawGitUrl(pluginUrl),
                    headers = headers,
                    timeout = 120,
                    cacheControlOverride = okhttp3.CacheControl.FORCE_NETWORK
                )
            } catch (e: CancellationException) {
                // (v0.2.4) Never launder a cancellation into
                // "download_failed": a withTimeout kill must propagate
                // as TimeoutCancellationException so the caller reports
                // an honest "timeout".
                throw e
            } catch (e: Exception) {
                // (v0.2.3) A socket timeout is a timeout, not a generic
                // download failure — the UI can say so honestly.
                // (v0.2.4) Retry transport failures; the partial file
                // keeps what arrived, so the next attempt resumes.
                val code = if (e is java.net.SocketTimeoutException) "timeout" else "download_failed"
                lastDownloadError = code
                EngineLogger.log("download", "GET failed ${file.name} (attempt $attempt/3): ${e.javaClass.simpleName} ${e.message}")
                if (e is java.io.IOException && attempt < 3) continue
                return PluginDownloadResult.Err(code, "Could not reach the server (${e.javaClass.simpleName})")
            }
            if (response.code == 416) {
                // (v0.2.4) Range not satisfiable — the partial is stale
                // (the file changed server-side). Drop it, start fresh.
                EngineLogger.log("download", "HTTP 416 for ${file.name}: dropping stale partial")
                partialFile.delete()
                partialHashFile.delete()
                if (attempt < 3) continue
                return PluginDownloadResult.Err("http_416", "Server rejected the resume (HTTP 416)")
            }
            if (!response.isSuccessful) {
                val code = "http_${response.code}"
                lastDownloadError = code
                EngineLogger.log("download", "HTTP ${response.code} for ${file.name} ($pluginUrl)")
                return PluginDownloadResult.Err(code, "Server returned HTTP ${response.code}")
            }
            val body = response.okhttpResponse.body
            if (body == null) {
                lastDownloadError = "download_empty"
                EngineLogger.log("download", "empty body for ${file.name}")
                return PluginDownloadResult.Err("download_empty", "Server returned an empty file")
            }
            // (v0.2.6) Validate the 206 Content-Range start BEFORE
            // appending: a server that answers 206 from the WRONG
            // offset would silently corrupt the file (resumed bytes
            // landing at the wrong position). On a mismatch, drop
            // the partial and retry from byte 0 (the next attempt
            // sends no Range header); on the last attempt fail
            // honestly instead of writing misaligned bytes.
            if (response.code == 206 && downloadedBytes > 0L) {
                val rangeStart = response.headers["Content-Range"]
                    ?.substringAfter("bytes ", "")
                    ?.substringBefore("-")
                    ?.toLongOrNull()
                if (rangeStart != downloadedBytes) {
                    EngineLogger.log(
                        "download",
                        "Content-Range mismatch for ${file.name}: server starts at $rangeStart, partial has $downloadedBytes — restarting from byte 0"
                    )
                    partialFile.delete()
                    partialHashFile.delete()
                    if (attempt < 3) continue
                    lastDownloadError = "download_failed"
                    return PluginDownloadResult.Err(
                        "download_failed",
                        "Server resume offset mismatch (Content-Range start $rangeStart != $downloadedBytes)"
                    )
                }
            }
            // (v0.2.4) 206 = the server honoured Range: append to the
            // partial. 200 after a Range request = the server ignored
            // it: discard the partial and write from byte 0.
            val append = response.code == 206 && downloadedBytes > 0L
            if (!append && downloadedBytes > 0L) {
                EngineLogger.log("download", "server ignored Range for ${file.name}: restarting from byte 0")
                partialFile.delete()
            }
            try {
                body.byteStream().use { stream ->
                    java.io.FileOutputStream(partialFile, append).use { out ->
                        stream.copyTo(out)
                    }
                }
            } catch (e: CancellationException) {
                // (v0.2.4) Same as the GET catch: propagate, never
                // relabel as "download_failed". Bytes already written
                // stay in the partial for the next attempt.
                throw e
            } catch (e: Exception) {
                // (v0.2.3) Same timeout mapping as the GET catch above.
                // (v0.2.4) Retry transport failures; bytes already
                // written stay in the partial for the next attempt.
                val code = if (e is java.net.SocketTimeoutException) "timeout" else "download_failed"
                lastDownloadError = code
                EngineLogger.log("download", "body read failed ${file.name} (attempt $attempt/3): ${e.message}")
                if (e is java.io.IOException && attempt < 3) continue
                return PluginDownloadResult.Err(code, "Download interrupted (${e.javaClass.simpleName})")
            }
            // A full body arrived this attempt: fall through to the
            // length / hash checks below.
            break
        }
        if (partialFile.length() == 0L) {
            partialFile.delete()
            partialHashFile.delete()
            lastDownloadError = "download_empty"
            EngineLogger.log("download", "0-byte download for ${file.name}")
            return PluginDownloadResult.Err("download_empty", "Downloaded file is empty")
        }

        // (v0.2.6) Repo-manifest size check (SitePlugin.fileSize,
        // present for all 88 live Phisher plugins): a truncated
        // download must not reach the hash gate as if it were whole.
        // The hash arbitrates when present — a size mismatch with a
        // MATCHING hash means the manifest size itself is stale, so
        // the file is accepted with a warning, never rejected on size
        // alone. With no hash to arbitrate, a size mismatch fails
        // honestly as download_incomplete.
        if (expectedFileSize != null && partialFile.length() != expectedFileSize) {
            val gotSize = partialFile.length()
            EngineLogger.log("download", "size mismatch ${file.name}: got $gotSize B, manifest says $expectedFileSize B")
            if (expectedFileHash == null) {
                partialFile.delete()
                partialHashFile.delete()
                lastDownloadError = "download_incomplete"
                return PluginDownloadResult.Err(
                    "download_incomplete",
                    "Downloaded $gotSize B, expected $expectedFileSize B"
                )
            }
        }

        if (expectedFileHash != null) {
            val downloadHash = sha256(partialFile)
            if (expectedFileHash != downloadHash) {
                partialFile.delete()
                partialHashFile.delete()
                lastDownloadError = "hash_mismatch"
                EngineLogger.log("download", "hash mismatch ${file.name}: expected $expectedFileHash got $downloadHash")
                return PluginDownloadResult.Err(
                    "hash_mismatch",
                    "Downloaded file failed its integrity check"
                )
            }
        }

        // We prefer the operation to be atomic
        try {
            try {
                Files.move(
                    partialFile.toPath(),
                    file.toPath(),
                    StandardCopyOption.REPLACE_EXISTING,
                    StandardCopyOption.ATOMIC_MOVE
                )
            } catch (_: AtomicMoveNotSupportedException) {
                Files.move(
                    partialFile.toPath(),
                    file.toPath(),
                    StandardCopyOption.REPLACE_EXISTING
                )
            }
        } catch (e: Exception) {
            partialFile.delete()
            partialHashFile.delete()
            lastDownloadError = "download_io"
            EngineLogger.log("download", "move failed ${file.name}: ${e.message}")
            return PluginDownloadResult.Err("download_io", "Could not save the file (${e.javaClass.simpleName})")
        }

        partialHashFile.delete()
        lastDownloadError = null
        EngineLogger.log("download", "downloaded ${file.name} (${file.length()} B)")
        return PluginDownloadResult.Ok(file)
    }

    fun getRepositories(): Array<RepositoryData> {
        return getKey<Array<RepositoryData>>(REPOSITORIES_KEY) ?: emptyArray()
    }

    // Don't want to read before we write in another thread
    private val repoLock = Mutex()
    suspend fun addRepository(repository: RepositoryData) {
        repoLock.withLock {
            // No duplicates, but we want the new repository instead of the old one
            var currentRepos = getRepositories()
            val index = currentRepos.indexOfFirst { it.url == repository.url }
            if(index == -1) {
                currentRepos += repository
            } else {
                /** We want to keep the ordering here, as that is the addition order */
                currentRepos[index] = repository
            }
            setKey(REPOSITORIES_KEY, currentRepos)
        }
        // (v0.2.1-p) A re-added / renamed repo must not serve a stale manifest.
        invalidateRepoCache(repository.url)
    }

    /**
     * Also deletes downloaded repository plugins
     */
    suspend fun removeRepository(context: Context, repository: RepositoryData) {
        val extensionsDir = File(context.filesDir, ONLINE_PLUGINS_FOLDER)

        repoLock.withLock {
            val currentRepos = getKey<Array<RepositoryData>>(REPOSITORIES_KEY) ?: emptyArray()
            // No duplicates
            val newRepos = currentRepos.filter { it.url != repository.url }
            setKey(REPOSITORIES_KEY, newRepos)
        }
        // (v0.2.1-p) Drop the cached manifest / plugin list with the repo.
        invalidateRepoCache(repository.url)

        val file = File(
            extensionsDir,
            getPluginSanitizedFileName(repository.url)
        )

        // Unload all plugins, not using deletePlugin since we
        // delete all data and files in deleteRepositoryData
        safe {
            file.listFiles { plugin: File ->
                unloadPlugin(plugin.absolutePath)
                false
            }
        }

        PluginManager.deleteRepositoryData(file.absolutePath)
    }
